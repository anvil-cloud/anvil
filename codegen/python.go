package codegen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type PythonGenerator struct{}

func (g *PythonGenerator) Name() string { return "python" }

func (g *PythonGenerator) Generate(schemas map[string]DSQLComponent, outDir string) error {
	for _, comp := range schemas {
		for _, s := range comp.Schemas {
			code := generatePython(s)
			path := filepath.Join(outDir, ToSnakeCase(s.Name)+".py")
			if err := os.WriteFile(path, []byte(code), 0o644); err != nil {
				return fmt.Errorf("writing %s: %w", path, err)
			}
		}
	}

	init := generatePythonInit(schemas)
	path := filepath.Join(outDir, "__init__.py")
	return os.WriteFile(path, []byte(init), 0o644)
}

func generatePython(s Schema) string {
	var b strings.Builder
	b.WriteString("# generated by anvil generate — do not edit\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("from dataclasses import dataclass\n")
	b.WriteString("from typing import Any, Optional\n")

	imports := pythonImports(s)
	if imports != "" {
		b.WriteString(imports)
	}
	b.WriteString("\n\n")

	for _, t := range s.Tables {
		writePythonTypes(&b, t)
	}

	writePythonQueries(&b, s)
	return b.String()
}

func writePythonTypes(b *strings.Builder, t Table) {
	row := ToPascalCase(t.Name) + "Row"
	ins := ToPascalCase(t.Name) + "Insert"
	upd := ToPascalCase(t.Name) + "Update"

	// Row
	fmt.Fprintf(b, "@dataclass\nclass %s:\n", row)
	requiredFirst := partitionColumns(t.Columns, func(c Column) bool { return c.NotNull })
	for _, c := range requiredFirst {
		pyType := pyType(c)
		if c.NotNull {
			fmt.Fprintf(b, "    %s: %s\n", c.Name, pyType)
		} else {
			fmt.Fprintf(b, "    %s: %s = None\n", c.Name, pyType)
		}
	}
	b.WriteString("\n\n")

	// Insert — PK required, columns with defaults are optional
	fmt.Fprintf(b, "@dataclass\nclass %s:\n", ins)
	insertCols := partitionColumns(t.Columns, func(c Column) bool {
		return insertRequired(t, c)
	})
	for _, c := range insertCols {
		required := insertRequired(t, c)
		if required {
			c2 := c
			c2.NotNull = true
			fmt.Fprintf(b, "    %s: %s\n", c.Name, pyType(c2))
		} else {
			fmt.Fprintf(b, "    %s: %s = None\n", c.Name, pyTypeNullable(c))
		}
	}
	b.WriteString("\n\n")

	// Update — all optional
	fmt.Fprintf(b, "@dataclass\nclass %s:\n", upd)
	for _, c := range t.Columns {
		pyType := pyTypeNullable(c)
		fmt.Fprintf(b, "    %s: %s = None\n", c.Name, pyType)
	}
	b.WriteString("\n\n")
}

func writePythonQueries(b *strings.Builder, s Schema) {
	className := ToPascalCase(s.Name) + "Queries"
	fmt.Fprintf(b, "class %s:\n", className)
	b.WriteString("    def __init__(self, conn) -> None:\n")
	b.WriteString("        self._conn = conn\n\n")

	for _, t := range s.Tables {
		propName := ToSnakeCase(t.Name)
		tqClass := ToPascalCase(t.Name) + "Queries"
		fmt.Fprintf(b, "    @property\n    def %s(self) -> %s:\n", propName, tqClass)
		fmt.Fprintf(b, "        return %s(self._conn)\n\n", tqClass)
	}
	b.WriteString("\n")

	for _, t := range s.Tables {
		writePythonTableQueries(b, s.Name, t)
	}
}

func writePythonTableQueries(b *strings.Builder, schemaName string, t Table) {
	row := ToPascalCase(t.Name) + "Row"
	ins := ToPascalCase(t.Name) + "Insert"
	upd := ToPascalCase(t.Name) + "Update"
	className := ToPascalCase(t.Name) + "Queries"
	qualifiedTable := schemaName + "." + t.Name

	colNames := make([]string, len(t.Columns))
	for i, c := range t.Columns {
		colNames[i] = c.Name
	}
	selectCols := strings.Join(colNames, ", ")

	fmt.Fprintf(b, "class %s:\n", className)
	b.WriteString("    def __init__(self, conn) -> None:\n")
	b.WriteString("        self._conn = conn\n\n")

	// find_by_id
	pkParams := makePyPKParams(t)
	pkWhere := makePyPKWhere(t, 1)
	pkArgs := makePyPKArgs(t)

	fmt.Fprintf(b, "    async def find_by_id(self, %s) -> Optional[%s]:\n", pkParams, row)
	fmt.Fprintf(b, "        row = await self._conn.fetchrow(\n")
	fmt.Fprintf(b, "            'SELECT %s FROM %s WHERE %s',\n", selectCols, qualifiedTable, pkWhere)
	fmt.Fprintf(b, "            %s,\n", pkArgs)
	b.WriteString("        )\n")
	fmt.Fprintf(b, "        return %s(**dict(row)) if row else None\n\n", row)

	// find_many
	fmt.Fprintf(b, "    async def find_many(self) -> list[%s]:\n", row)
	fmt.Fprintf(b, "        rows = await self._conn.fetch(\n")
	fmt.Fprintf(b, "            'SELECT %s FROM %s',\n", selectCols, qualifiedTable)
	b.WriteString("        )\n")
	fmt.Fprintf(b, "        return [%s(**dict(r)) for r in rows]\n\n", row)

	// insert
	fmt.Fprintf(b, "    async def insert(self, row: %s) -> %s:\n", ins, row)
	b.WriteString("        fields = {k: v for k, v in row.__dict__.items() if v is not None}\n")
	b.WriteString("        cols = list(fields.keys())\n")
	b.WriteString("        vals = list(fields.values())\n")
	b.WriteString("        placeholders = ', '.join(f'${i + 1}' for i in range(len(cols)))\n")
	b.WriteString("        col_str = ', '.join(cols)\n")
	b.WriteString("        # Unset columns are left out so the database applies their defaults.\n")
	b.WriteString("        if cols:\n")
	fmt.Fprintf(b, "            sql = f'INSERT INTO %s ({col_str}) VALUES ({placeholders}) RETURNING *'\n", qualifiedTable)
	b.WriteString("        else:\n")
	fmt.Fprintf(b, "            sql = 'INSERT INTO %s DEFAULT VALUES RETURNING *'\n", qualifiedTable)
	b.WriteString("        result = await self._conn.fetchrow(sql, *vals)\n")
	fmt.Fprintf(b, "        return %s(**dict(result))\n\n", row)

	// update
	pkOffset := len(t.PrimaryKey)
	fmt.Fprintf(b, "    async def update(self, %s, set_: %s) -> Optional[%s]:\n", pkParams, upd, row)
	b.WriteString("        fields = {k: v for k, v in set_.__dict__.items() if v is not None}\n")
	b.WriteString("        if not fields:\n")
	b.WriteString("            return None\n")
	b.WriteString("        cols = list(fields.keys())\n")
	b.WriteString("        vals = list(fields.values())\n")
	fmt.Fprintf(b, "        set_clause = ', '.join(f'{c} = ${i + %d}' for i, c in enumerate(cols))\n", pkOffset+1)

	whereParts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		whereParts[i] = fmt.Sprintf("%s = $%d", pk, i+1)
	}
	where := strings.Join(whereParts, " AND ")

	b.WriteString("        result = await self._conn.fetchrow(\n")
	fmt.Fprintf(b, "            f'UPDATE %s SET {set_clause} WHERE %s RETURNING *',\n", qualifiedTable, where)
	fmt.Fprintf(b, "            %s, *vals,\n", pkArgs)
	b.WriteString("        )\n")
	fmt.Fprintf(b, "        return %s(**dict(result)) if result else None\n\n", row)

	// delete
	fmt.Fprintf(b, "    async def delete(self, %s) -> bool:\n", pkParams)
	fmt.Fprintf(b, "        result = await self._conn.execute(\n")
	fmt.Fprintf(b, "            'DELETE FROM %s WHERE %s',\n", qualifiedTable, pkWhere)
	fmt.Fprintf(b, "            %s,\n", pkArgs)
	b.WriteString("        )\n")
	b.WriteString("        return result != 'DELETE 0'\n\n\n")
}

func generatePythonInit(schemas map[string]DSQLComponent) string {
	var b strings.Builder
	b.WriteString("# generated by anvil generate — do not edit\n\n")
	for _, comp := range schemas {
		for _, s := range comp.Schemas {
			file := ToSnakeCase(s.Name)
			b.WriteString(fmt.Sprintf("from .%s import *  # noqa: F401, F403\n", file))
		}
	}
	return b.String()
}

// Helpers

func pyType(c Column) string {
	m, ok := typeMappings[c.Type]
	if !ok {
		return "Any"
	}
	base := m.Python
	if !c.NotNull {
		return "Optional[" + base + "]"
	}
	return base
}

func pyTypeNullable(c Column) string {
	m, ok := typeMappings[c.Type]
	if !ok {
		return "Any"
	}
	return "Optional[" + m.Python + "]"
}

func pythonImports(s Schema) string {
	needsDatetime := false
	needsDecimal := false
	for _, t := range s.Tables {
		for _, c := range t.Columns {
			switch c.Type {
			case "date", "time", "timestamp", "timestamptz", "interval":
				needsDatetime = true
			case "numeric":
				needsDecimal = true
			}
		}
	}

	var parts []string
	if needsDatetime {
		parts = append(parts, "from datetime import date, datetime, time, timedelta")
	}
	if needsDecimal {
		parts = append(parts, "from decimal import Decimal")
	}
	if len(parts) == 0 {
		return ""
	}
	return "\n" + strings.Join(parts, "\n")
}

func partitionColumns(cols []Column, isRequired func(Column) bool) []Column {
	var required, optional []Column
	for _, c := range cols {
		if isRequired(c) {
			required = append(required, c)
		} else {
			optional = append(optional, c)
		}
	}
	return append(required, optional...)
}

func makePyPKParams(t Table) string {
	colMap := map[string]Column{}
	for _, c := range t.Columns {
		colMap[c.Name] = c
	}
	parts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		c := colMap[pk]
		c.NotNull = true
		parts[i] = fmt.Sprintf("%s: %s", pk, pyType(c))
	}
	return strings.Join(parts, ", ")
}

func makePyPKWhere(t Table, startIdx int) string {
	parts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		parts[i] = fmt.Sprintf("%s = $%d", pk, startIdx+i)
	}
	return strings.Join(parts, " AND ")
}

func makePyPKArgs(t Table) string {
	return strings.Join(t.PrimaryKey, ", ")
}
