package codegen

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// RustGenerator writes the typed DSQL client as a complete crate: outDir is
// the crate directory (gen/db by default), with a Cargo.toml whose
// dependencies and features are computed from the schemas, src/lib.rs, and
// one module per schema. The crate is Anvil-owned and fully rewritten on
// every generate; joining it to the Cargo workspace is the caller's job.
type RustGenerator struct{}

func (g *RustGenerator) Name() string { return "rust" }

// RustCrateName is the generated crate's package name: Lambdas depend on it
// as `db = { path = "..." }` and `use db::<schema>::...`.
const RustCrateName = "db"

func (g *RustGenerator) Generate(schemas map[string]DSQLComponent, outDir string) error {
	all := sortedSchemas(schemas)

	srcDir := filepath.Join(outDir, "src")
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", srcDir, err)
	}

	write := func(path, contents string) error {
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
		return nil
	}

	if err := write(filepath.Join(outDir, "Cargo.toml"), rustCargoToml(all)); err != nil {
		return err
	}

	keep := map[string]bool{"lib.rs": true}
	for _, s := range all {
		file := ToSnakeCase(s.Name) + ".rs"
		keep[file] = true
		if err := write(filepath.Join(srcDir, file), generateRust(s)); err != nil {
			return err
		}
	}
	if err := write(filepath.Join(srcDir, "lib.rs"), generateRustLib(all)); err != nil {
		return err
	}

	return removeStaleRust(srcDir, keep)
}

// sortedSchemas flattens every component's schemas in a stable order, so the
// generated files are identical run to run.
func sortedSchemas(schemas map[string]DSQLComponent) []Schema {
	var all []Schema
	for _, comp := range schemas {
		all = append(all, comp.Schemas...)
	}
	sort.Slice(all, func(i, j int) bool { return all[i].Name < all[j].Name })
	return all
}

// removeStaleRust deletes generated modules for schemas that no longer
// exist. Only files carrying the generated header are removed, so anything
// a user added by hand survives.
func removeStaleRust(srcDir string, keep map[string]bool) error {
	entries, err := os.ReadDir(srcDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || keep[e.Name()] || filepath.Ext(e.Name()) != ".rs" {
			continue
		}
		path := filepath.Join(srcDir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(data), rustGeneratedHeader) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

const rustGeneratedHeader = "// generated by anvil generate — do not edit\n"

func generateRust(s Schema) string {
	var b strings.Builder
	b.WriteString(rustGeneratedHeader)
	b.WriteString("\n")

	imports := rustImports(s)
	if imports != "" {
		b.WriteString(imports)
		b.WriteString("\n")
	}

	for _, t := range s.Tables {
		writeRustTypes(&b, t)
		b.WriteString("\n")
	}

	writeRustQueries(&b, s)
	return b.String()
}

func writeRustTypes(b *strings.Builder, t Table) {
	row := ToPascalCase(t.Name) + "Row"
	ins := ToPascalCase(t.Name) + "Insert"
	upd := ToPascalCase(t.Name) + "Update"

	pkSet := map[string]bool{}
	for _, pk := range t.PrimaryKey {
		pkSet[pk] = true
	}
	hasDefaultSet := map[string]bool{}
	for _, c := range t.Columns {
		if c.Default != "" {
			hasDefaultSet[c.Name] = true
		}
	}

	// Row
	fmt.Fprintf(b, "#[derive(Debug, Clone, Serialize, Deserialize)]\n")
	fmt.Fprintf(b, "pub struct %s {\n", row)
	for _, c := range t.Columns {
		rustT := rustType(c)
		fmt.Fprintf(b, "    pub %s: %s,\n", ToSnakeCase(c.Name), rustT)
	}
	b.WriteString("}\n\n")

	// Insert
	fmt.Fprintf(b, "#[derive(Debug, Clone, Serialize, Deserialize)]\n")
	fmt.Fprintf(b, "pub struct %s {\n", ins)
	for _, c := range t.Columns {
		required := pkSet[c.Name] || (c.NotNull && !hasDefaultSet[c.Name])
		if required {
			c2 := c
			c2.NotNull = true
			rustT := rustType(c2)
			fmt.Fprintf(b, "    pub %s: %s,\n", ToSnakeCase(c.Name), rustT)
		} else {
			rustT := rustTypeOption(c)
			fmt.Fprintf(b, "    pub %s: %s,\n", ToSnakeCase(c.Name), rustT)
		}
	}
	b.WriteString("}\n\n")

	// Update — all Option
	fmt.Fprintf(b, "#[derive(Debug, Clone, Default, Serialize, Deserialize)]\n")
	fmt.Fprintf(b, "pub struct %s {\n", upd)
	for _, c := range t.Columns {
		rustT := rustTypeOption(c)
		fmt.Fprintf(b, "    pub %s: %s,\n", ToSnakeCase(c.Name), rustT)
	}
	b.WriteString("}\n")
}

func writeRustQueries(b *strings.Builder, s Schema) {
	for _, t := range s.Tables {
		writeRustTableQueries(b, s.Name, t)
	}
}

func writeRustTableQueries(b *strings.Builder, schemaName string, t Table) {
	row := ToPascalCase(t.Name) + "Row"
	ins := ToPascalCase(t.Name) + "Insert"
	structName := ToPascalCase(t.Name) + "Queries"
	qualifiedTable := schemaName + "." + t.Name

	colNames := make([]string, len(t.Columns))
	for i, c := range t.Columns {
		colNames[i] = c.Name
	}
	selectCols := strings.Join(colNames, ", ")

	fmt.Fprintf(b, "\npub struct %s<'a> {\n    client: &'a Client,\n}\n\n", structName)

	fmt.Fprintf(b, "impl<'a> %s<'a> {\n", structName)
	fmt.Fprintf(b, "    pub fn new(client: &'a Client) -> Self {\n        Self { client }\n    }\n\n")

	// find_by_id
	pkParams := makeRustPKParams(t)
	pkWhere := makeRustPKWhere(t, 1)
	pkArgs := makeRustPKArgs(t)

	fmt.Fprintf(b, "    pub async fn find_by_id(&self, %s) -> Result<Option<%s>, Error> {\n", pkParams, row)
	fmt.Fprintf(b, "        let row = self.client\n")
	fmt.Fprintf(b, "            .query_opt(\n")
	fmt.Fprintf(b, "                \"SELECT %s FROM %s WHERE %s\",\n", selectCols, qualifiedTable, pkWhere)
	fmt.Fprintf(b, "                &[%s],\n", pkArgs)
	b.WriteString("            )\n            .await?;\n")
	b.WriteString("        Ok(row.map(|r| ")
	fmt.Fprintf(b, "%s {\n", row)
	for _, c := range t.Columns {
		fmt.Fprintf(b, "            %s: r.get(\"%s\"),\n", ToSnakeCase(c.Name), c.Name)
	}
	b.WriteString("        }))\n    }\n\n")

	// find_many
	fmt.Fprintf(b, "    pub async fn find_many(&self) -> Result<Vec<%s>, Error> {\n", row)
	fmt.Fprintf(b, "        let rows = self.client\n")
	fmt.Fprintf(b, "            .query(\"SELECT %s FROM %s\", &[])\n", selectCols, qualifiedTable)
	b.WriteString("            .await?;\n")
	b.WriteString("        Ok(rows.into_iter().map(|r| ")
	fmt.Fprintf(b, "%s {\n", row)
	for _, c := range t.Columns {
		fmt.Fprintf(b, "            %s: r.get(\"%s\"),\n", ToSnakeCase(c.Name), c.Name)
	}
	b.WriteString("        }).collect())\n    }\n\n")

	// insert
	fmt.Fprintf(b, "    pub async fn insert(&self, row: &%s) -> Result<%s, Error> {\n", ins, row)
	insertPlaceholders := make([]string, len(t.Columns))
	insertArgs := make([]string, len(t.Columns))
	for i, c := range t.Columns {
		insertPlaceholders[i] = fmt.Sprintf("$%d", i+1)
		insertArgs[i] = fmt.Sprintf("&row.%s", ToSnakeCase(c.Name))
	}
	fmt.Fprintf(b, "        let result = self.client\n")
	fmt.Fprintf(b, "            .query_one(\n")
	fmt.Fprintf(b, "                \"INSERT INTO %s (%s) VALUES (%s) RETURNING %s\",\n",
		qualifiedTable, strings.Join(colNames, ", "),
		strings.Join(insertPlaceholders, ", "), selectCols)
	fmt.Fprintf(b, "                &[%s],\n", strings.Join(insertArgs, ", "))
	b.WriteString("            )\n            .await?;\n")
	fmt.Fprintf(b, "        Ok(%s {\n", row)
	for _, c := range t.Columns {
		fmt.Fprintf(b, "            %s: result.get(\"%s\"),\n", ToSnakeCase(c.Name), c.Name)
	}
	b.WriteString("        })\n    }\n\n")

	// delete
	fmt.Fprintf(b, "    pub async fn delete(&self, %s) -> Result<bool, Error> {\n", pkParams)
	fmt.Fprintf(b, "        let n = self.client\n")
	fmt.Fprintf(b, "            .execute(\n")
	fmt.Fprintf(b, "                \"DELETE FROM %s WHERE %s\",\n", qualifiedTable, pkWhere)
	fmt.Fprintf(b, "                &[%s],\n", pkArgs)
	b.WriteString("            )\n            .await?;\n")
	b.WriteString("        Ok(n > 0)\n    }\n")

	b.WriteString("}\n")

	_ = ins // used above
}

func generateRustLib(schemas []Schema) string {
	var b strings.Builder
	b.WriteString(rustGeneratedHeader)
	b.WriteString("\n")
	for _, s := range schemas {
		fmt.Fprintf(&b, "pub mod %s;\n", ToSnakeCase(s.Name))
	}
	return b.String()
}

// Helpers

func rustType(c Column) string {
	m, ok := typeMappings[c.Type]
	if !ok {
		return "serde_json::Value"
	}
	base := m.Rust
	if !c.NotNull {
		return "Option<" + base + ">"
	}
	return base
}

func rustTypeOption(c Column) string {
	m, ok := typeMappings[c.Type]
	if !ok {
		return "Option<serde_json::Value>"
	}
	return "Option<" + m.Rust + ">"
}

// rustCargoToml is the generated crate's manifest. Its dependencies (and
// their features) follow from the column types the schemas use. Without the
// tokio-postgres integration features (with-uuid-1, with-chrono-0_4, …) and
// rust_decimal's db-tokio-postgres feature, the ToSql/FromSql impls are
// missing and the code fails to compile with cryptic trait-bound errors.
func rustCargoToml(schemas []Schema) string {
	var needsUUID, needsChrono, needsDecimal, needsJSON bool
	for _, s := range schemas {
		for _, t := range s.Tables {
			for _, c := range t.Columns {
				switch c.Type {
				case "uuid":
					needsUUID = true
				case "date", "time", "timestamp", "timestamptz":
					needsChrono = true
				case "numeric":
					needsDecimal = true
				case "json", "jsonb":
					needsJSON = true
				}
			}
		}
	}

	// tokio-postgres integration features, in declared order.
	var pgFeatures []string
	if needsUUID {
		pgFeatures = append(pgFeatures, "with-uuid-1")
	}
	if needsChrono {
		pgFeatures = append(pgFeatures, "with-chrono-0_4")
	}
	if needsJSON {
		pgFeatures = append(pgFeatures, "with-serde_json-1")
	}
	pgFeatureStr := ""
	if len(pgFeatures) > 0 {
		pgFeatureStr = fmt.Sprintf(", features = [%s]", quoteJoinRust(pgFeatures))
	}

	var b strings.Builder
	b.WriteString("# generated by anvil generate — do not edit. Rewritten on every\n")
	b.WriteString("# generate; dependencies follow the column types your schemas use.\n")
	fmt.Fprintf(&b, "[package]\nname = %q\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n", RustCrateName)
	b.WriteString("[dependencies]\n")
	b.WriteString("serde = { version = \"1\", features = [\"derive\"] }\n")
	fmt.Fprintf(&b, "tokio-postgres = { version = \"0.7\"%s }\n", pgFeatureStr)
	if needsUUID {
		b.WriteString("uuid = { version = \"1\", features = [\"serde\"] }\n")
	}
	if needsChrono {
		b.WriteString("chrono = { version = \"0.4\", features = [\"serde\"] }\n")
	}
	if needsDecimal {
		b.WriteString("rust_decimal = { version = \"1\", features = [\"serde\", \"db-tokio-postgres\"] }\n")
	}
	if needsJSON {
		b.WriteString("serde_json = \"1\"\n")
	}
	return b.String()
}

func quoteJoinRust(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(quoted, ", ")
}

func rustImports(s Schema) string {
	// Generated field/argument types use fully-qualified paths (uuid::Uuid,
	// rust_decimal::Decimal, chrono::DateTime<chrono::Utc>, chrono::NaiveDate,
	// serde_json::Value), so those crates need no `use`. Only the derive traits
	// and the query client/error are referenced by short name. Keeping the list
	// minimal avoids unused-import warnings regardless of which column types the
	// schema happens to use.
	if len(s.Tables) == 0 {
		return "use tokio_postgres::{Client, Error};\n"
	}
	return "use serde::{Deserialize, Serialize};\n" +
		"use tokio_postgres::{Client, Error};\n"
}

func makeRustPKParams(t Table) string {
	colMap := map[string]Column{}
	for _, c := range t.Columns {
		colMap[c.Name] = c
	}
	parts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		c := colMap[pk]
		c.NotNull = true
		rustT := rustType(c)
		if rustT == "String" {
			rustT = "&str"
		}
		parts[i] = fmt.Sprintf("%s: %s", ToSnakeCase(pk), rustT)
	}
	return strings.Join(parts, ", ")
}

func makeRustPKWhere(t Table, startIdx int) string {
	parts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		parts[i] = fmt.Sprintf("%s = $%d", pk, startIdx+i)
	}
	return strings.Join(parts, " AND ")
}

func makeRustPKArgs(t Table) string {
	parts := make([]string, len(t.PrimaryKey))
	for i, pk := range t.PrimaryKey {
		parts[i] = "&" + ToSnakeCase(pk)
	}
	return strings.Join(parts, ", ")
}
